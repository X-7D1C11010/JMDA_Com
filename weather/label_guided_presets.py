def build_preset(project_root,data_dir,output,method,target,seed=42,parameter_profile='reference'):
    root=Path(project_root).resolve()
    values=copy.deepcopy(REFERENCE_PARAMETERS[f'{method}_{target}']['arguments'])
    values.update(method=method,target=target,seed=seed,data_dir=str(data_dir),save_dir=str(output),device='cuda',
        target_class_matching='target_truth',matched_alignment_weight=5.,matched_alignment_margin=.2,
        matched_alignment_ramp_epochs=3,max_train_batches=0)
    values['target_batch_size']=values['batch_size']
    values['weights']=str(root/'pretrained_weights/torch/hub/checkpoints'/values['weights'])
    if values.get('ir_weights'):values['ir_weights']=str(root/'pretrained_weights/unip'/values['ir_weights'])
    if method=='dann' and target=='dark':
        values.update(adaptation_warmup_epochs=1,adaptation_ramp_epochs=5)
    if parameter_profile not in ('reference','conservative','lr_only'):
        raise ValueError('Unknown parameter profile')
    values['configuration_tag']={'reference':'reference','conservative':'conservative_v1','lr_only':'lr_only_v1'}[parameter_profile]
    if parameter_profile in ('conservative','lr_only'):
        # Scale explicit encoder overrides too: reducing base_lr alone would
        # otherwise leave their actual learning rates unchanged.
        for key in ('lr','image_lr_override','ir_lr_override','adversarial_lr_override'):
            if values.get(key) is not None:values[key]*=.5
    if parameter_profile=='conservative':
        values['weight_decay']=max(2*values['weight_decay'],5e-4)
        values['label_smoothing']=max(values.get('label_smoothing') or 0.,.1)
        clip=values.get('gradient_clip_norm') or 0.
        values['gradient_clip_norm']=min(clip,5.) if clip>0 else 5.
    return values

