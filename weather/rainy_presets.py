def arguments_for(method, project_root, lists, save_dir, seed):
    if method not in METHOD_ARGUMENTS or seed < 0:
        raise ValueError("Unknown method or negative seed")
    values = deepcopy(COMMON_ARGUMENTS)
    values.update(deepcopy(METHOD_ARGUMENTS[method]))
    root = Path(project_root).resolve()/"pretrained_weights"
    filename = ("convnext_small-0c510722.pth" if values["image_backbone"]=="convnext_small"
                else "resnet18-f37072fd.pth")
    values.update(data_dir=str(Path(lists).resolve()),save_dir=str(Path(save_dir).resolve()),seed=seed,
        weights=str(root/"torch/hub/checkpoints"/filename),
        prediction_teacher_weights=str(root/"torch/hub/checkpoints/resnet18-f37072fd.pth"),
        ir_weights=str(root/"unip/unip_vit_tiny_by_ibot_large.pth") if values["ir_backbone"] else None)
    return values
